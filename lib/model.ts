// Token Radar, model radar-2: comps-calibrated implied value.
//
// A pre-token protocol is worth what the market already pays for the same
// kind of protocol that already trades. The snapshot carries both sides of
// that comparison: live-token protocols with a market cap, and pre-token
// protocols with only TVL. So the model calibrates itself from the snapshot:
//
//   comp(category) = median(mcap_usd / tvl_usd) over live protocols in that
//                    category, shrunk toward the global median, clamped to
//                    [0.05, 0.65]; a category with fewer than three live
//                    protocols uses the global median instead
//   implied = tvl_usd x comp(category)
//                     x (1 + clamp(change_7d, -60, 120) / 100 x 0.6)
//                     x (0.6 + min(age_days, 1095) / 1095 x 0.4)
//                     x (1 + min(chains - 1, 4) x 0.03)
//
// No protocol name is ever special-cased: the same function scores every
// row, and every multiplier is shown in the dashboard so a reader can check
// the arithmetic against board.json. The starter's flat 0.25x TVL treated a
// lending protocol and a DEX as the same business; the snapshot says they
// are not (live lending trades near 0.13x TVL, live DEXes near 0.34x), so
// this model does not either. A protocol's implied value is the entry's own
// claim, never a promise and never a prediction of whether or when a token
// is issued.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

